#!/usr/bin/env python3
"""extras 桌面补丁、spec 改写与工作流接线的离线检查。

构建本身要下载 Fedora SRPM 并编译 KWin/GTK3，不在离线测试里跑。这里锁住
真正容易错的部分：包表、两个 GSD 补丁、spec 锚点、默认链没有桌面包，以及
extras workflow 是否真的接上了。
"""

import hashlib
import importlib.util
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts" / "build-fedora-desktop-patches.py"
EXTRAS_SCRIPT = ROOT / "scripts" / "build-piano-extras.py"
WORKFLOW = ROOT / ".github" / "workflows" / "build-piano-extras.yml"
DEFAULT_WORKFLOW = ROOT / ".github" / "workflows" / "build-piano-rpms.yml"
MAKEFILE = ROOT / "Makefile"
PROFILES = ROOT / "scripts" / "profiles" / "fedora-desktops.json"
FINALIZER = ROOT / "scripts" / "finalize-fedora-rootfs.py"
SUNUEFI = Path(__import__("os").environ.get(
    "PIANO_TEST_SUNUEFI", ROOT / "build/test-sources/sunuefi"))

HEX64 = re.compile(r"^[0-9a-f]{64}$")


def load_module():
    spec = importlib.util.spec_from_file_location("desktop_patches", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def test_package_table(module):
    assert {entry["source"] for entry in module.PACKAGES} == {
        "gnome-settings-daemon", "kwin", "gtk3"}
    for entry in module.PACKAGES:
        name = entry["source"]
        assert entry["url"].endswith(".src.rpm"), name
        assert "kojipkgs.fedoraproject.org" in entry["url"], name
        assert ".fc45.src.rpm" in entry["url"], name
        for key in ("srpm_sha256", "spec_sha256", "tarball_sha256"):
            assert HEX64.match(entry[key]), f"{name}: {key} is not a sha256"
        assert entry["patches"], name
        for patch_file, patch_sha, copied in entry["patches"]:
            assert patch_file.endswith(".patch") and HEX64.match(patch_sha), name
            assert copied.endswith(".patch") and "/" not in copied, name
        assert set(entry["required"]) <= set(entry["runtime"]), name
        assert entry["desktops"], name
        assert entry["release"].endswith(".piano1"), name
        assert entry["binary"] in entry["required"], name
    gsd = next(e for e in module.PACKAGES if e["source"] == "gnome-settings-daemon")
    assert gsd["binary"] == "gnome-settings-daemon-piano"
    assert gsd["desktops"] == ("gnome",)
    assert len(gsd["patches"]) == 2, gsd["patches"]
    gtk3 = next(e for e in module.PACKAGES if e["source"] == "gtk3")
    assert set(gtk3["desktops"]) == {"gnome", "kde", "niri", "hyprland"}
    kwin = next(e for e in module.PACKAGES if e["source"] == "kwin")
    assert kwin["desktops"] == ("kde",)


GSD_SPEC = """Name:           gnome-settings-daemon
Release:        %autorelease
Source0:        https://download.gnome.org/sources/%{name}/%{gnome_major_version}/%{name}-%{gnome_tarball_version}.tar.xz

%prep
%autosetup -p1 -n %{name}-%{gnome_tarball_version}

%build
%meson

%install
%meson_install
%find_lang %{name} --with-gnome

%files -f %{name}.lang
%{_libexecdir}/gsd-*

%package devel
Requires:       %{name}%{?_isa} = %{version}-%{release}

%changelog
## START: Generated by rpmautospec
"""


def test_gsd_spec_rewrite(module):
    rewritten = module.adapt_gsd(GSD_SPEC)
    assert "Name:           gnome-settings-daemon-piano" in rewritten
    assert "Release:        1.piano1%{?dist}" in rewritten
    assert "Patch999:        piano-ambient-profile.patch" in rewritten
    assert "Patch998:        piano-keyboard-backlight.patch" in rewritten
    assert ("%autosetup -p1 -n gnome-settings-daemon-"
            "%{gnome_tarball_version}") in rewritten
    assert "%find_lang gnome-settings-daemon --with-gnome" in rewritten
    assert "%files -f gnome-settings-daemon.lang" in rewritten
    assert "sources/gnome-settings-daemon/%{gnome_major_version}" in rewritten
    assert "%{name}-%{gnome_tarball_version}.tar.xz" not in rewritten
    assert "Provides:       gnome-settings-daemon = %{version}-%{release}" in rewritten
    assert "Obsoletes:      gnome-settings-daemon < %{version}-%{release}" in rewritten
    assert "Conflicts:      gnome-settings-daemon%{?_isa}" in rewritten
    assert "Provides:       gnome-settings-daemon-devel = %{version}-%{release}" in rewritten
    assert "Obsoletes:      gnome-settings-daemon-devel < %{version}-%{release}" in rewritten
    final = module.add_changelog(rewritten, "51.1", "1.piano1", "note")
    assert "* Wed Nov 11 2026 FFT-infra <dev@piano.invalid> - 51.1-1.piano1" in final
    assert final.count("* Wed Nov 11 2026") == 1


def test_same_name_specs(module):
    kwin = module.adapt_kwin("Name:    kwin\nRelease: 3%{?dist}\n%prep\n%changelog\n")
    assert "Release: 3.piano1%{?dist}" in kwin
    assert "Patch999:        piano-kwin-hdr.patch" in kwin
    gtk3 = module.adapt_gtk3("Name:    gtk3\nRelease: %autorelease\n%prep\n%changelog\n")
    assert "Release: 6.piano1%{?dist}" in gtk3
    assert "Patch999:        piano-gtk3-xi2.patch" in gtk3


def test_rewrites_refuse_drifted_specs(module):
    for call, spec in (
            (module.adapt_gsd, GSD_SPEC.replace("Name:           gnome-settings-daemon\n", "")),
            (module.adapt_kwin, "Release: 4%{?dist}\n%prep\n%changelog\n"),
            (module.adapt_gtk3, "Release: 6%{?dist}\n%prep\n%changelog\n")):
        try:
            call(spec)
        except ValueError:
            pass
        else:
            raise AssertionError(f"drifted spec was accepted: {call.__name__}")
    for bad in ("%prep\n%prep\n", "Patch999: old.patch\n%prep\n"):
        try:
            module.add_patches(bad, ["a.patch", "b.patch"])
        except ValueError:
            pass
        else:
            raise AssertionError("an occupied or duplicated %prep section was accepted")


def test_workflow_wires_extras():
    text = WORKFLOW.read_text()
    for token in ("scripts/build-piano-extras.py",
                  "--sunuefi build/sources/sunuefi",
                  "--output build/piano-extras",
                  "build/piano-extras/rpms",
                  "build/piano-extras/srpms",
                  "PIANO_EXTRAS_BUILT_NOT_DEVICE_VERIFIED",
                  "piano-gnome-extras", "piano-kde-extras"):
        assert token in text, f"extras workflow does not carry {token}"
    default = DEFAULT_WORKFLOW.read_text()
    for token in ("build-fedora-desktop-patches.py",
                  "gnome-settings-daemon-piano", "kwin", "gtk3"):
        assert token not in default, f"default workflow still carries {token}"
    assert "cargo rust libjpeg-turbo-devel libyuv-devel glibc-static" in default
    assert EXTRAS_SCRIPT.is_file()


def test_profiles_and_finalizer():
    profiles = json.loads(PROFILES.read_text())
    for desktop, profile in profiles.items():
        for name in ("gnome-settings-daemon-piano", "kwin", "gtk3", "ibus"):
            assert name not in (profile.get("dnf_packages") or []), (desktop, name)
            assert name not in (profile.get("required_packages") or []), (desktop, name)

    finalizer = FINALIZER.read_text()
    assert "verify_desktop_packages" not in finalizer
    assert "DESKTOP_PATCH_RELEASE" not in finalizer
    assert '"ambient-enabled": "false"' in finalizer


def test_sunuefi_patch_hashes(module):
    patches = SUNUEFI / "patches"
    if not patches.is_dir():
        print("SKIP: SunUEFI checkout unavailable; patch hashes were not checked")
        return
    for entry in module.PACKAGES:
        for relative, expected, _ in entry["patches"]:
            path = patches / relative
            assert path.is_file(), f"missing patch: {path}"
            digest = hashlib.sha256(path.read_bytes()).hexdigest()
            assert digest == expected, f"{path} changed: {digest}"


def test_makefile_registers_test():
    assert "tests/check_fedora_desktop_packages.py" in MAKEFILE.read_text()


def main():
    module = load_module()
    test_package_table(module)
    test_gsd_spec_rewrite(module)
    test_same_name_specs(module)
    test_rewrites_refuse_drifted_specs(module)
    test_workflow_wires_extras()
    test_profiles_and_finalizer()
    test_sunuefi_patch_hashes(module)
    test_makefile_registers_test()
    print("OK: extras packages are pinned, rewritten and kept out of the default chain")


if __name__ == "__main__":
    main()
